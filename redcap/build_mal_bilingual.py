def mlm_hash(text):
    """REDCap MLM stores the first 10 hex chars of sha1(original text)."""
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:10]


def tr(text):
    return f"<br><span style=\"{TR_STYLE}\">{text}</span>"


def add_after_span_title(html, title):
    """Append translated title inside the first heading <span>...</span>."""
    return re.sub(r"(<span[^>]*>)(.*?)(</span>)", lambda m: f"{m.group(1)}{m.group(2)} / {title}{m.group(3)}", html, count=1)


def scale_html(html, title, items, line_tag):
    html = add_after_span_title(html, title)
    for key, text in items.items():
        pattern = re.compile(rf"({line_tag(key)}.*?)(<br>|\n\s*</div>)", re.S)
        html, n = pattern.subn(lambda m: m.group(1) + tr(text) + m.group(2), html, count=1)
        assert n == 1, f"line {key} not found"
    return html


def table_html(html, lang):
    cols = lang["columns"]
    headers = re.findall(r"<th[^>]*>(.*?)</th>", html)
    assert len(headers) == len(cols)
    for en, local in zip(headers, cols):
        html = html.replace(f">{en}</th>", f">{en}{tr(local)}</th>", 1)
    for i, text in enumerate(lang["tasks"], start=1):
        pattern = re.compile(rf"(<td[^>]*>{i}\. [^<]*)(</td>)")
        html, n = pattern.subn(lambda m: m.group(1) + tr(f"{i}. {text}") + m.group(2), html, count=1)
        assert n == 1, f"task {i} not found"
    assert len(lang["tasks"]) == 30
    return html


def build_entries(lang, rows):
    def entry(var, label=None, header=None):
        e = {"id": var, "form": FORM}
        if header is not None:
            e["header"] = {"hash": mlm_hash(rows[var]["Section Header"]), "translation": header}
        e["label"] = {"hash": mlm_hash(rows[var]["Field Label"]), "translation": label or ""}
        return e

    sec_as = rows["mal_scoring_as"]["Section Header"]
    sec_tbl = rows["mal_table"]["Section Header"]
    return [
        entry(
            "mal_scoring_as",
            scale_html(rows["mal_scoring_as"]["Field Label"], lang["as_title"], lang["as"], lambda k: rf"<b>{k}</b> &mdash;"),
            header=f"{sec_as} <br> {lang['title']}",
        ),
        entry(
            "mal_scoring_hw",
            scale_html(rows["mal_scoring_hw"]["Field Label"], lang["hw_title"], lang["hw"], lambda k: rf"<b>{k}</b> &mdash;"),
        ),
        entry(
            "mal_why_codes",
            scale_html(rows["mal_why_codes"]["Field Label"], lang["codes_title"], lang["codes"], lambda k: rf"<b>{k}\.</b>"),
        ),
        entry("mal_table", table_html(rows["mal_table"]["Field Label"], lang), header=f"{sec_tbl} <br> {lang['title']}"),
    ]


def main():
    with open(FINAL_CSV, encoding="utf-8") as f:
        rows = {r["Variable / Field Name"]: r for r in csv.DictReader(f) if r["Form Name"] == FORM}

    for lang in (TA, TE):
        entries = build_entries(lang, rows)
        ids = {e["id"] for e in entries}
        for doc_name in lang["docs"]:
            path = TRANSLATION_DIR / doc_name
            with open(path, encoding="utf-8") as f:
                doc = json.load(f)
            kept = [x for x in doc["fieldTranslations"] if not (x["form"] == FORM and x["id"] in ids)]
            doc["fieldTranslations"] = kept + entries
            with open(path, "w", encoding="utf-8") as f:
                json.dump(doc, f, ensure_ascii=False, indent=4)
            print(f"[OK] {doc_name}: {len(entries)} MAL entries")


if __name__ == "__main__":
    main()
